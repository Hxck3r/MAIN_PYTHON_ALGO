def _section(title: str, body: str) -> str:
    return f"\n\n{'=' * 70}\n{title}\n{'=' * 70}\n{body}"


def build_system_prompt(
    config: AssistantConfig,
    context: ProjectContext,
    include_state: bool = True,
) -> str:
    """Собирает полный системный промпт из доктрины и живого контекста проекта."""
    parts = [PERSONA, "\n\n" + OVERFITTING_DOCTRINE, "\n\n" + WORKING_RULES]

    # Карта проекта: дерево, реестр стратегий, ключевое API.
    parts.append(_section(
        "КАРТА ПРОЕКТА (актуальная структура)",
        context.file_tree(max_depth=2),
    ))
    parts.append(_section(
        "ЗАРЕГИСТРИРОВАННЫЕ СТРАТЕГИИ (реестр STRATEGIES)",
        context.registered_strategies(),
    ))
    parts.append(_section("СПРАВКА ПО ПАКЕТУ backtester", _BACKTESTER_REFERENCE))
    parts.append(_section("КАК ЧИТАТЬ МЕТРИКИ", _METRICS_GUIDE))

    # Контракт написания стратегий (AI_STRATEGY_RULES.md), если включён.
    if config.include_rules:
        rules = _load_rules(context)
        if rules:
            parts.append(_section(
                "КОНТРАКТ СТРАТЕГИЙ (AI_STRATEGY_RULES.md — соблюдать строго)",
                rules,
            ))

    # Живой снимок состояния GUI.
    if include_state:
        parts.append(_section(
            "ТЕКУЩЕЕ СОСТОЯНИЕ ПРИЛОЖЕНИЯ (на момент сообщения)",
            context.app_state(),
        ))

    return "".join(parts)


def _load_rules(context: ProjectContext) -> str:
    try:
        return context.read_file("AI_STRATEGY_RULES.md")
    except Exception:  # noqa: BLE001
        return ""


