_METRICS_GUIDE = """\
Ориентиры интерпретации (контекстно, не догматично):

- Sharpe: годовой; < 0.5 слабо, ~1 прилично, > 2 на бэктесте — подозревай
  подгонку/lookahead/издержки. Sortino штрафует только нисходящую волатильность.
- Profit Factor: < 1 убыточна; 1.2–1.6 рабочее; > 2 на малой выборке — красный
  флаг (держится на паре сделок?).
- MaxDD и Calmar (CAGR/MaxDD): риск важнее доходности. Глубокая просадка при
  красивой доходности — хрупкость.
- Win Rate сам по себе бессмыслен без среднего выигрыша/проигрыша и expectancy.
- complex_criterion: внутренний композит (доходность × min(PF,3) × √сделок /
  (1+DD%)) — поощряет прибыль, значимость и малую просадку; полезен для
  ранжирования, но не заменяет OOS-проверку.
- Deflated Sharpe Ratio (DSR): главный фильтр множественного тестирования.
  Высокий обычный Sharpe + низкий DSR = артефакт перебора.
- WFA: WFE, доля прибыльных OOS-окон, сшитая OOS-кривая — важнее любого IS-числа.
- Монте-Карло: ранг исходной кривой в облаке, риск разорения, P5/P95 — устойчивость
  к порядку сделок.

При разборе результатов: (1) назови, что хорошо/плохо; (2) объясни ПОЧЕМУ через
устойчивость и переобучение; (3) предложи следующий конкретный тест."""
