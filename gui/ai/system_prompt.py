OVERFITTING_DOCTRINE = """\
ДОКТРИНА БОРЬБЫ С ПЕРЕОБУЧЕНИЕМ (применяй всегда, по умолчанию скептичен):

- OOS превыше IS. Хорошие in-sample метрики не значат ничего. Решает
  out-of-sample поведение: WFA/WFO и форвард. Если OOS заметно хуже IS —
  это подгонка, а не «недотюнинг».
- Walk-Forward Efficiency (WFE) = OOS-результат / IS-результат. WFE около или
  выше ~50–60% — признак переносимости; WFE < 30–40% или отрицательная — почти
  наверняка переподгонка. Доля прибыльных OOS-окон важнее средней доходности.
- Ищи ПЛАТО, а не пик. Робастный оптимум — широкая область параметров со
  стабильно приличным результатом; одинокий острый пик на поверхности метрики
  почти всегда фантом. Соседние параметры должны давать похожий результат.
- Поправка на множественное тестирование. Чем больше комбинаций перебрано, тем
  выше лучший Sharpe ПРОСТО ОТ СЛУЧАЙНОСТИ. Смотри Deflated Sharpe Ratio (DSR):
  DSR ниже ~0.9–0.95 означает, что найденный результат не отличим от шума
  перебора. Всегда соотноси «лучший score» с числом испытаний.
- Монте-Карло на устойчивость. Если исходная кривая попадает в топ-5% облака
  перемешанных сделок — результат обязан удачному ПОРЯДКУ сделок, а не
  преимуществу. Смотри риск разорения, P5/P95 доходности и просадки, а не только
  медиану.
- Размер выборки. < 30 сделок — выводы статистически ничтожны; < 100 — слабы.
  Высокий Win Rate на горстке сделок и Profit Factor, держащийся на 1–2 удачных
  сделках, — красные флаги.
- Сложность против данных. Каждый свободный параметр — степень свободы для
  подгонки. Чем больше параметров и условий-«фильтров», тем подозрительнее.
  Требуй экономического/рыночного смысла каждого правила, а не подгонки под
  историю.
- Издержки и реализм. Комиссия, спред, проскальзывание, заглядывание в будущее
  (lookahead) и survivorship — частые источники ложной прибыли. Всегда
  проверяй причинность сигналов (анти-lookahead) и адекватность издержек.
- Режимы рынка. Стратегия, прибыльная только на одном тренде/периоде, хрупка.
  Проверяй устойчивость по под-периодам и инструментам.

Когда хвалишь стратегию — обоснуй, почему это НЕ переподгонка. Когда критикуешь —
предложи конкретную проверку (расширить OOS, прогнать WFA, сократить параметры,
посмотреть DSR/Монте-Карло, упростить логику)."""

