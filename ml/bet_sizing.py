"""Размер ставки из вероятности модели (López de Prado, AFML гл. 10).

Зачем это нужно
---------------
Бинарный порог («в рынке / не в рынке») выбрасывает информацию: модель, уверенная на
0.55, и модель, уверенная на 0.95, торгуются одинаково. Bet sizing переводит
**калиброванную** вероятность в долю позиции — больше риска на уверенных сигналах,
меньше на пограничных. Это снижает дисперсию эквити и повышает риск-скорректированную
доходность при том же наборе сделок.

Методы (величина в ``[0, 1]``, знак/сторону задаёт сигнал отдельно):

* ``confidence`` — статистика AFML: ``m = 2·Φ(z) − 1``, ``z = (p − ½)/√(p(1−p))``;
  гладко растёт от 0 у ½ к 1 у краёв (рекомендуется для калиброванных вероятностей);
* ``linear`` — линейно ``|2p − 1|`` (просто и устойчиво без калибровки).

Чистый ``math``/numpy, без Qt/ML — тестируется headless и используется и в стратегии,
и в GUI (кривая размера ставки).
"""
from __future__ import annotations

import math

import numpy as np

_SQRT2 = math.sqrt(2.0)


def _norm_cdf(z: float) -> float:
    """Функция распределения стандартной нормали через ``math.erf`` (без scipy)."""
    return 0.5 * (1.0 + math.erf(z / _SQRT2))


def bet_size_from_proba(p: float, method: str = "confidence") -> float:
    """Величина ставки в ``[0, 1]`` для вероятности класса ``p`` (сторона — отдельно).

    Симметрична относительно ½: |p−½| определяет уверенность независимо от направления.
    """
    p = float(min(max(p, 1e-6), 1.0 - 1e-6))
    if method == "linear":
        return abs(2.0 * p - 1.0)
    # confidence (по умолчанию): z-статистика отклонения от случайности.
    z = (p - 0.5) / math.sqrt(p * (1.0 - p))
    return abs(2.0 * _norm_cdf(z) - 1.0)


def bet_size_curve(method: str = "confidence", n: int = 101) -> tuple[np.ndarray, np.ndarray]:
    """Сетка ``(p, размер)`` для отрисовки кривой размера ставки в GUI."""
    ps = np.linspace(0.0, 1.0, n)
    sizes = np.array([bet_size_from_proba(float(p), method) for p in ps], dtype=float)
    return ps, sizes
